"""Copy the agent's model list and error catalog into the static portal, which publishes only portal/.

    python scripts/sync_portal_data.py          write the portal's four generated data files
    python scripts/sync_portal_data.py --check  fail if any is out of date

The public demo gets its cards from the same registry the lab uses, so its words, commands and costs can't drift from the product.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "portal/lab-data.js"
MODEL_FIELDS = ("ollama_tag", "family", "about", "params_b", "quant", "size_gb", "min_ram_gb", "license_gate")
ERROR_FIELDS = ("id", "title", "patterns", "cause", "fix", "learn")


def render() -> str:
    models = json.loads((ROOT / "agent/skill/models.json").read_text(encoding="utf-8"))["models"]
    errors = json.loads((ROOT / "agent/skill/error_catalog.json").read_text(encoding="utf-8"))["errors"]
    data = {"models": [{k: m[k] for k in MODEL_FIELDS} for m in models],
            "errors": [{k: e[k] for k in ERROR_FIELDS} for e in errors]}
    return ("/* Generated by scripts/sync_portal_data.py from agent/skill. Do not edit. */\n"
            "globalThis.LocalLabCatalog = " + json.dumps(data, indent=1, ensure_ascii=False) + ";\n")


PREVIEW = ROOT / "portal/preview-data.js"
DEMO_MODEL = "qwen2.5:1.5b"
DEMO_STEPS = ("check_hardware", "install_runtime", "start_runtime", "pull_model", "first_prompt")


def render_preview() -> str:
    """The demo's cards, built by the registry for a fixed laptop so the file is the same on every machine."""
    sys.path.insert(0, str(ROOT / "agent"))
    from telemetry_agent.actions import REGISTRY
    model = next(m for m in json.loads((ROOT / "agent/skill/models.json").read_text(encoding="utf-8"))["models"] if m["ollama_tag"] == DEMO_MODEL)
    rt = {"installed": True, "running": False, "models": [], "broken_models": []}
    cards = {}
    for platform, system, start in (("mac", "Darwin", "open -a Ollama"), ("windows", "Windows", "Start menu > Ollama")):
        ctx = {"model": model, "name": DEMO_MODEL, "rt": rt, "system": system, "cli": "ollama", "app": "Ollama", "start": start}
        cards[platform] = [REGISTRY[action].step(ctx) for action in DEMO_STEPS]
    samples = json.loads((ROOT / "agent/skill/preview_samples.json").read_text(encoding="utf-8"))
    samples.pop("_note", None)
    data = {"model": DEMO_MODEL, "size_gb": model["size_gb"], "cards": cards, "samples": samples}
    return ("/* Generated by scripts/sync_portal_data.py from the action registry and agent/skill/preview_samples.json. Do not edit. */\n"
            "globalThis.LocalLabPreview = " + json.dumps(data, indent=1, ensure_ascii=False) + ";\n")


CATALOG = ROOT / "portal/catalog-data.js"
MEASURED = ROOT / "portal/measured-data.js"
CARD_FIELDS = ("title", "kind", "what", "why", "does", "undo", "command", "link", "risk")
PLATFORMS = (("mac", "Darwin", "open -a Ollama", {"name": "Homebrew", "cli": "brew", "installed": True}),
             ("windows", "Windows", "Start menu > Ollama", {"name": "winget", "cli": "winget", "installed": True}))


def render_catalog() -> str:
    """Every setup the lab offers, step by step, as the registry would show it on a laptop with nothing installed yet."""
    sys.path.insert(0, str(ROOT / "agent"))
    from telemetry_agent.actions import REGISTRY
    from telemetry_agent.apps import APPS, remove_command
    from telemetry_agent.recipes import load_recipes
    models = {m["ollama_tag"]: m for m in json.loads((ROOT / "agent/skill/models.json").read_text(encoding="utf-8"))["models"]}
    rt = {"installed": False, "running": False, "models": [], "broken_models": []}
    card = lambda step: {k: step[k] for k in CARD_FIELDS}

    def app_ctx(app_id, system, manager):
        return {"app": APPS[app_id], "name": APPS[app_id]["name"], "manager": manager, "system": system, "installed_at": None, "model": None}

    recipes = []
    for r in load_recipes().values():
        steps, adds = {}, 0.0
        for platform, system, start, manager in PLATFORMS:
            cards = []
            for item in r["steps"]:
                if item["action"] == "install_app":
                    ctx = app_ctx(item["app"], system, manager)
                else:
                    ctx = {"model": models.get(item.get("model")), "name": item.get("model"), "rt": rt, "system": system, "cli": "ollama", "app": "Ollama", "start": start}
                cards.append(card(REGISTRY[item["action"]].step(ctx)))
            cards.append(card(REGISTRY["check_recipe"].step({"recipe": r, "name": r["title"]})))
            steps[platform] = cards
        for item in r["steps"]:
            adds += APPS[item["app"]]["size_gb"] if item["action"] == "install_app" else models[item["model"]]["size_gb"] if item["action"] == "pull_model" else 0
        recipes.append({"id": r["id"], "title": r["title"], "for": r["for"], "why": r["why"], "review": r["review"], "adds_gb": round(adds, 1), "steps": steps})
    apps = []
    for app_id, app in APPS.items():
        entry = {"id": app_id, "name": app["name"], "what": app["what"], "size_gb": app["size_gb"], "site": app["site"], "install": {}, "remove": {}}
        for platform, system, _, manager in PLATFORMS:
            ctx = app_ctx(app_id, system, manager)
            entry["install"][platform] = card(REGISTRY["install_app"].step(ctx))
            entry["remove"][platform] = remove_command(ctx)
        apps.append(entry)
    return ("/* Generated by scripts/sync_portal_data.py from the action registry and agent/skill/recipes.json. Do not edit. */\n"
            "globalThis.LocalLabCatalogSetups = " + json.dumps({"recipes": recipes, "apps": apps}, indent=1, ensure_ascii=False) + ";\n")


def render_measured() -> str:
    """What real laptops measured, from the anonymous session files people chose to share in evaluation/measurements/.

    Every file is validated and its numbers are recomputed from its runs. A file can't say who sent it, so results are
    grouped by kind of laptop (chip and memory), not counted as separate laptops."""
    import statistics
    sys.path.insert(0, str(ROOT / "agent"))
    from telemetry_agent import protocol
    kinds = {}
    files = sorted((ROOT / "evaluation/measurements").glob("*.json"))
    for path in files:
        doc = protocol.load_session(path)
        if doc["data_kind"] != "measured":
            raise ValueError(f"{path.name} is not measured data.")
        summary = protocol.summarize_runs(doc["runs"])
        if not summary["valid_runs"] or summary.get("median_tps") is None:
            continue
        d = doc["device"]
        ram = round(d["total_ram_gib"])
        kind = kinds.setdefault((d["cpu_model"], ram), {"device": f"{d['cpu_model']}, {ram} GB", "os": d["os"], "ram_gb": ram, "models": {}})
        kind["models"].setdefault(doc["model"]["name"], []).append((summary, doc["created_at"][:10]))
    out = []
    for kind in kinds.values():
        rows = []
        for model, sessions in sorted(kind["models"].items()):
            tps = [s["median_tps"] for s, _ in sessions]
            ttft = [s["median_ttft_ms"] for s, _ in sessions if s.get("median_ttft_ms") is not None]
            peak = [s["peak_ram_mb"] for s, _ in sessions if s.get("peak_ram_mb") is not None]
            rows.append({"model": model, "sessions": len(sessions), "runs": sum(s["valid_runs"] for s, _ in sessions),
                         "tps": round(statistics.median(tps), 1), "tps_low": round(min(tps), 1), "tps_high": round(max(tps), 1),
                         "ttft_ms": round(statistics.median(ttft)) if ttft else None, "peak_mib": round(max(peak)) if peak else None,
                         "last": max(day for _, day in sessions)})
        out.append({**{k: kind[k] for k in ("device", "os", "ram_gb")}, "models": rows})
    data = {"sessions": sum(r["sessions"] for k in out for r in k["models"]), "kinds": sorted(out, key=lambda k: k["device"])}
    return ("/* Generated by scripts/sync_portal_data.py from evaluation/measurements/. Do not edit. */\n"
            "globalThis.LocalLabMeasured = " + json.dumps(data, indent=1, ensure_ascii=False) + ";\n")


def main(check: bool = False) -> int:
    files = ((TARGET, render), (PREVIEW, render_preview), (CATALOG, render_catalog), (MEASURED, render_measured))
    if check:
        stale = [path.name for path, make in files if not path.is_file() or path.read_text(encoding="utf-8") != make()]
        if stale:
            print(f"portal/{' and portal/'.join(stale)} out of date. Run: python scripts/sync_portal_data.py")
            return 1
        return 0
    for path, make in files:
        path.write_text(make(), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
